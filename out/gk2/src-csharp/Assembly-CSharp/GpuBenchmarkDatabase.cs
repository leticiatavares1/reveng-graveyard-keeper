	public static int GetBenchmarkPoints()
	{
		return GetBenchmarkPoints(SystemInfo.graphicsDeviceName, SystemInfo.graphicsDeviceVendorID, SystemInfo.graphicsDeviceID);
	}

	public static int GetBenchmarkPoints(string gpuName, int vendorId, int deviceId)
	{
		string text = Normalize(gpuName);
		for (int i = 0; i < s_names.Length; i++)
		{
			NameEntry nameEntry = s_names[i];
			if (text.Contains(nameEntry.Match))
			{
				return nameEntry.Points;
			}
		}
		if (vendorId != 0 && deviceId != 0)
		{
			for (int j = 0; j < s_pci.Length; j++)
			{
				PciEntry pciEntry = s_pci[j];
				if (pciEntry.Vendor == vendorId && pciEntry.Device == deviceId)
				{
					return pciEntry.Points;
				}
			}
		}
		return -1;
	}

	private static string Normalize(string s)
	{
		if (string.IsNullOrEmpty(s))
		{
			return string.Empty;
		}
		s = s.ToLowerInvariant();
		char[] array = new char[s.Length];
		int num = 0;
		bool flag = true;
		foreach (char c in s)
		{
			if (char.IsLetterOrDigit(c))
			{
				array[num++] = c;
				flag = false;
			}
			else if (!flag)
			{
				array[num++] = ' ';
				flag = true;
			}
		}
		if (num > 0 && array[num - 1] == ' ')
		{
			num--;
		}
		return new string(array, 0, num);
	}
