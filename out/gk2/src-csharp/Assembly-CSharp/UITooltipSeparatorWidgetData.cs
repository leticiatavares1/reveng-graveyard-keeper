{
	public int spaceDown;

	public int spaceUp;

	public UITooltipSeparatorWidgetData()
	{
	}

	public UITooltipSeparatorWidgetData(int spaceDown, int spaceUp)
	{
		this.spaceDown = spaceDown;
		this.spaceUp = spaceUp;
	}
}
